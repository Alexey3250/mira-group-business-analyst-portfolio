const translations = { en, ru } as const;

type I18nContextValue = {
  locale: Locale;
  t: Translations;
  tr: (value: string) => string;
  toggle: () => void;
};

const I18nCtx = createContext<I18nContextValue>({
  locale: "en",
  t: en,
  tr: (value) => value,
  toggle: () => {},
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("en");
  const toggle = useCallback(() => setLocale((current) => (current === "en" ? "ru" : "en")), []);
  const tr = useCallback(
    (value: string) => {
      if (locale !== "ru") return value;
      if (ruText[value]) return ruText[value];

      const trend = value.startsWith("↑") ? "↑ " : value.startsWith("↓") ? "↓ " : "";
      const normalized = value
        .replace(/^↑\s*/, "")
        .replace(/^↓\s*/, "")
        .replace(/\s+—\s+/g, " - ")
        .replace(/\s+→\s+/g, " -> ")
        .replace(/\s+·\s+/g, " / ");

      return `${trend}${ruText[normalized] ?? value}`;
    },
    [locale],
  );
  const value = useMemo(() => ({ locale, t: translations[locale], tr, toggle }), [locale, tr, toggle]);

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  return useContext(I18nCtx);
}
